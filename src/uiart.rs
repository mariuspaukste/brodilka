/// White glyphs on transparent, one cell per character, and each glyph's advance.
pub fn font() -> (Vec<u8>, usize, usize, Vec<u8>) {
    let (w, h) = (FONT_W * 95, FONT_H);
    let mut rgba = vec![0u8; w * h * 4];
    let mut adv = vec![0u8; 95];
    for (g, src) in GLYPHS.iter().enumerate() {
        let rows: Vec<&str> = src.split('/').collect();
        let gw = rows.iter().map(|r| r.len()).max().unwrap_or(0);
        adv[g] = (gw + 1) as u8;
        for (y, row) in rows.iter().enumerate().take(FONT_H) {
            for (x, ch) in row.bytes().enumerate().take(FONT_W) {
                if ch == b'#' {
                    let i = (y * w + g * FONT_W + x) * 4;
                    rgba[i..i + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    (rgba, w, h, adv)
}

fn hash(x: i32, y: i32, s: u32) -> f32 {
    let mut h = (x as u32).wrapping_mul(0x8da6_b343)
        ^ (y as u32).wrapping_mul(0xd816_3841)
        ^ s.wrapping_mul(0xcb1a_b31f);
    h ^= h >> 13;
    h = h.wrapping_mul(0x5bd1_e995);
    h ^= h >> 15;
    (h & 0xffff) as f32 / 65535.0
}

/// smooth periodic value noise
fn noise(x: f32, y: f32, period: i32, s: u32) -> f32 {
    let (xi, yi) = (x.floor() as i32, y.floor() as i32);
    let (fx, fy) = (x - xi as f32, y - yi as f32);
    let (sx, sy) = (fx * fx * (3.0 - 2.0 * fx), fy * fy * (3.0 - 2.0 * fy));
    let p = |a: i32| a.rem_euclid(period);
    let v = |a: i32, b: i32| hash(p(a), p(b), s);
    let top = v(xi, yi) + (v(xi + 1, yi) - v(xi, yi)) * sx;
    let bot = v(xi, yi + 1) + (v(xi + 1, yi + 1) - v(xi, yi + 1)) * sx;
    top + (bot - top) * sy
}

fn put(rgba: &mut [u8], w: usize, x: usize, y: usize, c: [f32; 3], a: u8) {
    let i = (y * w + x) * 4;
    rgba[i] = c[0].clamp(0.0, 255.0) as u8;
    rgba[i + 1] = c[1].clamp(0.0, 255.0) as u8;
    rgba[i + 2] = c[2].clamp(0.0, 255.0) as u8;
    rgba[i + 3] = a;
}

/// A seamless 64×64 dark tooled-leather panel.
pub fn panel() -> (Vec<u8>, usize, usize) {
    let (w, h) = (64usize, 64usize);
    let mut rgba = vec![0u8; w * h * 4];
    for y in 0..h {
        for x in 0..w {
            let (fx, fy) = (x as f32, y as f32);
            let n = noise(fx / 8.0, fy / 8.0, 8, 1) * 0.6
                + noise(fx / 4.0, fy / 4.0, 16, 2) * 0.3
                + noise(fx / 2.0, fy / 2.0, 32, 3) * 0.1;
            // fine creases running across the hide
            let crease = (noise(fx / 16.0, fy / 3.0, 4, 4) - 0.5).abs() < 0.035;
            let pore = hash(x as i32, y as i32, 9) > 0.93;
            let mut k = 0.72 + n * 0.5;
            if crease {
                k *= 0.78;
            }
            if pore {
                k *= 0.85;
            }
            let base = [44.0, 32.0, 22.0];
            put(
                &mut rgba,
                w,
                x,
                y,
                [base[0] * k, base[1] * k, base[2] * k],
                255,
            );
        }
    }
    (rgba, w, h)
}

/// A 12×12 nine-slice frame: a bronze bevel with rivets in the corners
/// (slice 4 px; the middle is transparent).
pub fn frame() -> (Vec<u8>, usize, usize) {
    let (w, h) = (12usize, 12usize);
    let mut rgba = vec![0u8; w * h * 4];
    let bronze = [150.0f32, 112.0, 52.0];
    for y in 0..h {
        for x in 0..w {
            let d = x.min(y).min(w - 1 - x).min(h - 1 - y);
            if d >= 4 {
                continue;
            }
            // outer black line, light bevel, flat face, dark inner lip
            let lit = x + y < w; // upper-left half catches the light
            let k = match d {
                0 => 0.0,
                1 => {
                    if lit {
                        1.45
                    } else {
                        0.95
                    }
                }
                2 => 1.0 + hash(x as i32, y as i32, 5) * 0.12,
                _ => 0.45,
            };
            let mut c = [bronze[0] * k, bronze[1] * k, bronze[2] * k];
            let corner = (x < 4 || x >= w - 4) && (y < 4 || y >= h - 4);
            if corner && (1..3).contains(&(x % 8)) && (1..3).contains(&(y % 8)) {
                // a rivet head
                let hi = (x % 8 == 1) && (y % 8 == 1);
                c = if hi {
                    [235.0, 210.0, 150.0]
                } else {
                    [90.0, 66.0, 30.0]
                };
            }
            put(&mut rgba, w, x, y, c, 255);
        }
    }
    (rgba, w, h)
}
